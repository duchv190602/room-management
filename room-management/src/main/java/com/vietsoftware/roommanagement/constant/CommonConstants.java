package com.vietsoftware.roommanagement.constant;

/**
 * Common constants used across the Room Management Application.
 */
public final class CommonConstants {

    /**
     * Private constructor to prevent instantiation of utility class.
     */
    private CommonConstants() {}

    /**
     * Integer constant representation of zero.
     */
    public static final int ZERO = 0;

    /**
     * Integer constant representation of one.
     */
    public static final int ONE = 1;
    /**
     * Integer constant representation of twenty.
     */
    public static final int TWENTY = 20;
    /**
     * Integer constant representation of one hundred.
     */
    public static final int ONE_HUNDRED = 100;
    /**
     * Integer constant representation of five hundred.
     */
     public static final int FIVE_HUNDRED = 500;
    /**
     * Empty string constant.
     */
    public static final String EMPTY = "";

    /**
     * Space string constant.
     */
    public static final String SPACE = " ";

    /**
     * Comma string constant.
     */
    public static final String COMMA = ",";

    /**
     * Wildcard string constant used in SQL LIKE queries.
     */
    public static final String LIKE_WILDCARD = "%";
}

